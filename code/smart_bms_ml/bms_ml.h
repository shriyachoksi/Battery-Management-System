// ML engine for the ML-enhanced Smart BMS (v2).
//
// Plain C++ with no Arduino dependencies, so the same code runs on the ESP32
// and in the host parity test (ml/tests). ml/bms_reference.py is the Python
// mirror used for training and evaluation - keep the two in step.
//
// Engine::update() runs once per valid sample (1 Hz):
//   1. pushes V/I/T into a 60-sample window and derives features from it
//      (window-average current, voltage slope, temperature slope);
//   2. once the window is "settled" (full, and 3 minutes clear of any
//      load/charger switching), a small MLP estimates SoC from those features and a
//      Gaussian mixture model scores how unusual the cell's behaviour is;
//   3. Coulomb counting is pulled toward the MLP estimate, and the anomaly
//      score is debounced into a flag;
//   4. the original v1 estimator (OCV table + Coulomb counting) runs
//      unchanged alongside, so the two can be compared.
//
// Weights and thresholds come from ml_model.h, generated by ml/train_models.py.

#pragma once

#include <math.h>
#include "ml_model.h"

namespace bmsml
{
using namespace bmsml_model;

inline float clampf(float x, float lo, float hi)
{
    return x < lo ? lo : (x > hi ? hi : x);
}

// ── v1 OCV table (from the original sketch) ──
const float OCV_TABLE[][2] = {
    {3.00f, 0}, {3.20f, 5}, {3.40f, 15}, {3.60f, 30}, {3.70f, 45}, {3.80f, 60}, {3.90f, 75}, {4.00f, 88}, {4.10f, 95}, {4.20f, 100}};
const int OCV_POINTS = 10;

inline float ocvToSoC(float voltage)
{
    if (voltage <= OCV_TABLE[0][0])
        return OCV_TABLE[0][1];
    if (voltage >= OCV_TABLE[OCV_POINTS - 1][0])
        return OCV_TABLE[OCV_POINTS - 1][1];

    for (int i = 0; i < OCV_POINTS - 1; i++)
    {
        if (voltage >= OCV_TABLE[i][0] && voltage <= OCV_TABLE[i + 1][0])
        {
            float slope = (OCV_TABLE[i + 1][1] - OCV_TABLE[i][1]) /
                          (OCV_TABLE[i + 1][0] - OCV_TABLE[i][0]);
            return OCV_TABLE[i][1] + slope * (voltage - OCV_TABLE[i][0]);
        }
    }
    return 50.0f;
}

// ── Feature window ───────────────────────────
struct Features
{
    float voltage;      // V, newest sample
    float current_A;    // A, newest sample (positive = discharge)
    float temp_C;       // C, newest sample
    float currentAvg_A; // A, mean over the window
    float dVdt_mVmin;   // least-squares voltage slope over the window, mV/min
    float dTdt_Cmin;    // least-squares temperature slope over the window, C/min
};

class FeatureWindow
{
public:
    void reset()
    {
        count = 0;
        head = 0;
        sinceStep = 0;
    }

    void push(float v, float i_mA, float t)
    {
        if (count > 0)
        {
            // A jump between consecutive samples means the load or charger
            // switched; the cell isn't steady-state again until its
            // polarisation has relaxed, SETTLE_SAMPLES later.
            int last = (head + FEATURE_WINDOW - 1) % FEATURE_WINDOW;
            bool step = fabsf(v - vBuf[last]) > STEP_VOLTAGE_V || fabsf(i_mA - iBuf[last]) > STEP_CURRENT_MA;
            sinceStep = step ? 0 : (sinceStep < SETTLE_SAMPLES ? sinceStep + 1 : SETTLE_SAMPLES);
        }
        vBuf[head] = v;
        iBuf[head] = i_mA;
        tBuf[head] = t;
        head = (head + 1) % FEATURE_WINDOW;
        if (count < FEATURE_WINDOW)
            count++;
    }

    // Full window, and SETTLE_SAMPLES step-free samples since the last switch.
    bool settled() const
    {
        return count == FEATURE_WINDOW && sinceStep >= SETTLE_SAMPLES;
    }

    Features features() const
    {
        int start = (head + FEATURE_WINDOW - count) % FEATURE_WINDOW;
        float v0 = vBuf[start];
        float t0 = tBuf[start];
        float xMean = (float)(count - 1) * 0.5f;
        float sxx = 0, sxv = 0, sxt = 0, iSum = 0;
        for (int k = 0; k < count; k++)
        {
            int idx = (start + k) % FEATURE_WINDOW;
            float x = (float)k - xMean;
            sxx += x * x;
            sxv += x * (vBuf[idx] - v0); // offsets keep the float sums small; the slope is unchanged
            sxt += x * (tBuf[idx] - t0);
            iSum += iBuf[idx];
        }
        int newest = (head + FEATURE_WINDOW - 1) % FEATURE_WINDOW;
        const float perMin = 60000.0f / SAMPLE_PERIOD_MS;

        Features f;
        f.voltage = vBuf[newest];
        f.current_A = iBuf[newest] / 1000.0f;
        f.temp_C = tBuf[newest];
        f.currentAvg_A = count > 0 ? iSum / (float)count / 1000.0f : 0;
        f.dVdt_mVmin = sxx > 0 ? sxv / sxx * 1000.0f * perMin : 0;
        f.dTdt_Cmin = sxx > 0 ? sxt / sxx * perMin : 0;
        return f;
    }

private:
    float vBuf[FEATURE_WINDOW];
    float iBuf[FEATURE_WINDOW];
    float tBuf[FEATURE_WINDOW];
    int head = 0;
    int count = 0;
    int sinceStep = 0;
};

// ── Models ───────────────────────────────────
// SoC MLP: 5 inputs -> tanh -> tanh -> SoC in %.
inline float predictSoc(const Features &f)
{
    float x[SOC_IN] = {f.voltage, f.current_A, f.temp_C, f.currentAvg_A, f.dVdt_mVmin};
    for (int i = 0; i < SOC_IN; i++)
        x[i] = (x[i] - SOC_X_MEAN[i]) / SOC_X_STD[i];

    float h1[SOC_H1];
    for (int j = 0; j < SOC_H1; j++)
    {
        float s = SOC_B1[j];
        for (int i = 0; i < SOC_IN; i++)
            s += SOC_W1[j][i] * x[i];
        h1[j] = tanhf(s);
    }

    float h2[SOC_H2];
    for (int j = 0; j < SOC_H2; j++)
    {
        float s = SOC_B2[j];
        for (int i = 0; i < SOC_H1; i++)
            s += SOC_W2[j][i] * h1[i];
        h2[j] = tanhf(s);
    }

    float y = SOC_B3;
    for (int j = 0; j < SOC_H2; j++)
        y += SOC_W3[j] * h2[j];
    return clampf(y * 100.0f, 0, 100);
}

// Anomaly score: negative log-likelihood of the window's behaviour under a
// Gaussian mixture fitted to normal operation. Higher = more unusual.
inline float anomalyScore(const Features &f, float socMl)
{
    float x[GMM_D] = {f.currentAvg_A, f.dVdt_mVmin, f.dTdt_Cmin, socMl};
    for (int d = 0; d < GMM_D; d++)
        x[d] /= GMM_SCALE[d];

    float logp[GMM_K];
    float best = -INFINITY;
    for (int k = 0; k < GMM_K; k++)
    {
        float diff[GMM_D];
        for (int d = 0; d < GMM_D; d++)
            diff[d] = x[d] - GMM_MEAN[k][d];
        float q = 0;
        for (int r = 0; r < GMM_D; r++)
            for (int c = 0; c < GMM_D; c++)
                q += diff[r] * GMM_PREC[k][r][c] * diff[c];
        logp[k] = GMM_LOGNORM[k] - 0.5f * q;
        if (logp[k] > best)
            best = logp[k];
    }
    float sum = 0;
    for (int k = 0; k < GMM_K; k++)
        sum += expf(logp[k] - best);
    return -(best + logf(sum));
}

// ── Engine ───────────────────────────────────
struct Output
{
    bool mlReady;       // window settled: socMl and anomalyScore are fresh
    Features features;  // valid when mlReady
    float socMl;        // latest MLP estimate, % (NAN until the first settled window)
    float anomalyScore; // NAN when not mlReady
    bool anomaly;       // debounced anomaly flag
    float socV1;        // original v1 estimate, %
    bool chargingV1;    // v1 charging detection
    float socFused;     // v2 estimate: Coulomb counting corrected by the MLP, %
};

class Engine
{
public:
    float ratedCapacity_mAh = 2500.0f;  // v1 estimator, as in the original sketch
    float usableCapacity_mAh = 2500.0f; // rated x SoH, used by the fused estimator

    Output out;

    Engine() { reset(); }

    void reset()
    {
        window.reset();
        v1Init = false;
        v1Soc = v1SocFiltered = v1PrevVoltage = 0;
        v1RisingCount = 0;
        prevLoadOn = false;
        fusedInit = false;
        fused = 0;
        above = below = 0;
        out = Output();
        out.socMl = NAN;
        out.anomalyScore = NAN;
        out.socV1 = NAN;
        out.socFused = NAN;
    }

    // One validated sample. dt_s is the time since the previous valid sample.
    const Output &update(float voltage, float current_mA, float temp_C, bool loadOn, float dt_s)
    {
        // A gap means samples were lost (invalid readings or a stalled loop):
        // the window no longer holds a contiguous minute, so start it over.
        if (dt_s > GAP_FACTOR * SAMPLE_PERIOD_MS / 1000.0f)
            window.reset();
        if (dt_s > MAX_DT_S)
            dt_s = MAX_DT_S;

        updateV1(voltage, current_mA, loadOn, dt_s);

        window.push(voltage, current_mA, temp_C);
        out.mlReady = window.settled();
        out.anomalyScore = NAN;
        if (out.mlReady)
        {
            out.features = window.features();
            out.socMl = predictSoc(out.features);
            out.anomalyScore = anomalyScore(out.features, out.socMl);
        }

        updateDetector();
        updateFusion(voltage, current_mA, dt_s);
        return out;
    }

private:
    FeatureWindow window;

    bool v1Init;
    float v1Soc, v1SocFiltered, v1PrevVoltage;
    int v1RisingCount;
    bool prevLoadOn;

    bool fusedInit;
    float fused;

    int above, below;

    // The original sketch's estimator, logic unchanged.
    void updateV1(float voltage, float current_mA, bool loadOn, float dt_s)
    {
        if (loadOn && !prevLoadOn)
            v1RisingCount = 0; // the 'D' command reset this in the original sketch
        prevLoadOn = loadOn;

        bool isCharging = false;
        if (!loadOn && v1PrevVoltage > 0.0f)
        {
            float delta = voltage - v1PrevVoltage;
            if (delta > 0.003f)
                v1RisingCount++;
            else if (delta < -0.003f)
                v1RisingCount--;
            v1RisingCount = v1RisingCount < 0 ? 0 : (v1RisingCount > 20 ? 20 : v1RisingCount);
            isCharging = (v1RisingCount >= 5) && (voltage < 4.18f);
        }
        v1PrevVoltage = voltage;

        if (!v1Init)
        {
            v1Soc = ocvToSoC(voltage);
            v1SocFiltered = v1Soc;
            v1Init = true;
        }

        if (loadOn && current_mA > 5)
            v1Soc -= (current_mA * (dt_s / 3600.0f) / ratedCapacity_mAh) * 100;
        else if (isCharging)
            v1Soc = 0.98f * v1Soc + 0.02f * ocvToSoC(voltage);
        else
            v1Soc = 0.97f * v1Soc + 0.03f * ocvToSoC(voltage);

        v1Soc = clampf(v1Soc, 0, 100);
        v1SocFiltered = (1 - V1_SOC_ALPHA) * v1SocFiltered + V1_SOC_ALPHA * v1Soc;
        out.socV1 = v1SocFiltered;
        out.chargingV1 = isCharging;
    }

    // Coulomb counting tracks fast changes; the MLP removes its drift (wrong
    // capacity, sensor offset, missed charge current) a little each sample.
    void updateFusion(float voltage, float current_mA, float dt_s)
    {
        if (!fusedInit)
        {
            fused = ocvToSoC(voltage);
            fusedInit = true;
        }
        if (fabsf(current_mA) > CC_DEADBAND_MA)
            fused -= current_mA * (dt_s / 3600.0f) / usableCapacity_mAh * 100.0f;
        if (out.mlReady)
        {
            bool resting = fabsf(out.features.currentAvg_A) * 1000.0f < REST_CURRENT_MA;
            float gain = resting ? FUSION_GAIN_REST : FUSION_GAIN_LOAD;
            fused += gain * (out.socMl - fused);
        }
        fused = clampf(fused, 0, 100);
        out.socFused = fused;
    }

    // Raise the flag after ANOMALY_PERSIST over-threshold samples in a row,
    // clear it after ANOMALY_CLEAR normal ones.
    void updateDetector()
    {
        if (!out.mlReady)
        {
            above = 0;
            return;
        }
        if (out.anomalyScore > ANOMALY_THRESHOLD)
        {
            above++;
            below = 0;
            if (above >= ANOMALY_PERSIST)
                out.anomaly = true;
        }
        else
        {
            below++;
            above = 0;
            if (below >= ANOMALY_CLEAR)
                out.anomaly = false;
        }
    }
};

} // namespace bmsml
